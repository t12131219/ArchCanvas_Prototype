#!/usr/bin/env python3
"""Validate and refresh the Transformer catalog and its source-atomic copy.

The project ships one checked-in, source-grounded model. Its figures and
editor payloads are generated by ``draw_transformer.py``; this utility only
keeps catalog metadata in sync and deliberately does not import arbitrary
models or adapt unrelated SVG examples.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
CASE_ID = "01093cc06a87b35a"
ATOMIC_CASE_ID = "01093cc06a87b35b"
VIEWS = (("overview", "概览"), ("modules", "内部模块"), ("detailed", "算子详细"))


def load_case(view):
    path = ROOT / "data" / "cases" / f"{CASE_ID}-{view}.json"
    if not path.is_file():
        raise FileNotFoundError(path)
    value = json.loads(path.read_text(encoding="utf-8"))
    if value.get("caseId") != CASE_ID or value.get("viewKey") != view:
        raise ValueError(f"invalid Transformer case payload: {path}")
    return path, value


def load_atomic_case():
    view = "source-atomic"
    path = ROOT / "data" / "cases" / f"{ATOMIC_CASE_ID}-{view}.json"
    if not path.is_file():
        raise FileNotFoundError(path)
    value = json.loads(path.read_text(encoding="utf-8"))
    if value.get("caseId") != ATOMIC_CASE_ID or value.get("viewKey") != view:
        raise ValueError(f"invalid source-atomic payload: {path}")
    return path, value


def build_catalog():
    views = []
    for view, label in VIEWS:
        path, value = load_case(view)
        svg = ROOT / value["source"]
        if not svg.is_file():
            raise FileNotFoundError(svg)
        views.append({
            "key": view,
            "label": label,
            "asset": f"data/cases/{CASE_ID}-{view}.js",
            "json": str(path.relative_to(ROOT)),
            "nodes": len(value.get("nodes", [])),
            "edges": len(value.get("edges", [])),
            "svg": value["source"],
            "ir": value.get("irSource"),
        })
    generated = ROOT / "snapshots" / "transformer_programmatic_guide" / "generated"
    evidence = []
    for name in ("source_evidence.json", "semantic_ir.json", "layout_checks.json"):
        path = generated / name
        if path.is_file():
            evidence.append({"path": str(path.relative_to(ROOT)), "title": f"Transformer / {name}", "bytes": path.stat().st_size})
    atomic_path, atomic = load_atomic_case()
    atomic_view = {
        "key": "source-atomic",
        "label": "源码原子图",
        "asset": f"data/cases/{ATOMIC_CASE_ID}-source-atomic.js",
        "json": str(atomic_path.relative_to(ROOT)),
        "nodes": len(atomic.get("nodes", [])),
        "edges": len(atomic.get("edges", [])),
        "svg": atomic["source"],
        "ir": atomic.get("irSource"),
        "atomicity": atomic.get("sourceAtomicStandard", {}).get("name"),
        "sourceAtomicCounts": atomic.get("sourceAtomicCounts"),
    }
    return {
        "schema": "summary-merge/1",
        "cases": [{
            "id": CASE_ID,
            "title": "Transformer",
            "collection": "transformer_programmatic_guide",
            "historical": False,
            "origin": "transformer_programmatic_guide/generated",
            "views": views,
            "sourceIndex": "snapshots/transformer_programmatic_guide/generated/index.html",
        }, {
            "id": ATOMIC_CASE_ID,
            "title": "Transformer · 源码原子粒度",
            "collection": "transformer_programmatic_guide",
            "historical": False,
            "origin": "transformer_programmatic_guide/generated",
            "views": [atomic_view],
            "sourceIndex": "snapshots/transformer_programmatic_guide/generated/index.html",
            "sourceAtomic": {**atomic.get("sourceAtomicStandard", {}), "counts": atomic.get("sourceAtomicCounts")},
        }],
        "evidence": evidence,
        "counts": {"cases": 2, "active": 2, "historical": 0, "views": len(views) + 1,
                   "snapshotFiles": sum(1 for _ in generated.rglob("*"))},
        "inputs": ["transformer_programmatic_guide"],
        "errors": [],
    }


def main():
    catalog = build_catalog()
    (ROOT / "data" / "catalog.json").write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "data" / "catalog.js").write_text("window.SummaryCatalog=" + json.dumps(catalog, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(json.dumps(catalog["counts"], ensure_ascii=False))


if __name__ == "__main__":
    main()
